#!/usr/bin/env python3
"""Generate per-scene kitty colour snippets from data/looks.json.

Apply one to the current kitty window with:
    kitten @ --match id:$KITTY_WINDOW_ID set-colors kitty/xiaoke-code.conf

Claude Code's own theme only paints its UI; kitty's background, foreground and
16 ANSI colours stay whatever the terminal profile says. These snippets make
the two agree.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "looks.json"
OUT = ROOT / "kitty"


def rgb(color: str) -> tuple[int, int, int]:
    value = color.lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def hexed(value: tuple[float, float, float]) -> str:
    return "#" + "".join(f"{max(0, min(255, round(c))):02x}" for c in value)


def mix(a: str, b: str, t: float) -> str:
    ar, ag, ab = rgb(a)
    br, bg, bb = rgb(b)
    return hexed((ar + (br - ar) * t, ag + (bg - ag) * t, ab + (bb - ab) * t))


def shift(color: str, mode: str, t: float) -> str:
    return mix(color, "#ffffff" if mode == "dark" else "#000000", t)


def build(look: dict) -> list[tuple[str, str]]:
    mode = look["mode"]
    paper = look["paper"]
    roles = look["roles"]
    anchors = look["anchors"]
    tp = anchors["text-primary"]
    accent, danger, success, warning, pro = (
        roles["accent"], roles["danger"], roles["success"], roles["warning"], roles["pro"],
    )
    black = mix(paper, "#000000", 0.45 if mode == "dark" else 0.82)
    white = mix(paper, "#ffffff", 0.35 if mode == "dark" else 0.65)
    magenta = mix(pro, danger, 0.5)
    cyan = mix(pro, success, 0.55)

    return [
        ("background", paper),
        ("foreground", tp),
        ("cursor", accent),
        ("cursor_text_color", paper),
        ("selection_background", mix(accent, paper, 0.55)),
        ("selection_foreground", tp),
        ("color0", black),
        ("color8", mix(black, tp, 0.45)),
        ("color1", danger),
        ("color9", shift(danger, mode, 0.18)),
        ("color2", success),
        ("color10", shift(success, mode, 0.18)),
        ("color3", warning),
        ("color11", shift(warning, mode, 0.18)),
        ("color4", pro),
        ("color12", shift(pro, mode, 0.18)),
        ("color5", magenta),
        ("color13", shift(magenta, mode, 0.18)),
        ("color6", cyan),
        ("color14", shift(cyan, mode, 0.18)),
        ("color7", white),
        ("color15", mix(white, "#ffffff", 0.45)),
    ]


def main() -> None:
    looks = json.loads(DATA.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    for look in looks:
        lines = [
            f"# 小克 · {look['title']} ({look['id']}, {look['mode']})",
            "# generated by tools/gen_kitty.py",
            *[f"{name} {value}" for name, value in build(look)],
        ]
        path = OUT / f"xiaoke-{look['id']}.conf"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
